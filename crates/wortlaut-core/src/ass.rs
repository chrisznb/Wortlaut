#[cfg(test)]
mod tests {
    use super::*;
    use crate::style::{HighlightMode, StylePreset};

    fn words(spec: &[(&str, u64, u64)]) -> Vec<Word> {
        spec.iter()
            .map(|(t, a, b)| Word::new(*t, *a, *b))
            .collect()
    }

    fn fill_style() -> SubtitleStyle {
        StylePreset::KaraokeLine.style()
    }

    /// Pull every `\k<number>` out of the script, in order.
    fn k_values(ass: &str) -> Vec<u64> {
        let mut out = Vec::new();
        let mut rest = ass;
        while let Some(pos) = rest.find("\\k") {
            rest = &rest[pos + 2..];
            let digits: String = rest.chars().take_while(|c| c.is_ascii_digit()).collect();
            if !digits.is_empty() {
                out.push(digits.parse().unwrap());
            }
        }
        out
    }

    fn dialogue_lines(ass: &str) -> Vec<&str> {
        ass.lines().filter(|l| l.starts_with("Dialogue:")).collect()
    }

    #[test]
    fn header_has_the_sections_libass_needs() {
        let ass = build_ass(&words(&[("hallo", 0, 400)]), &fill_style());

        assert!(ass.starts_with("[Script Info]\n"), "script info must come first");
        for needle in [
            "ScriptType: v4.00+",
            "PlayResX: 1080",
            "PlayResY: 1920",
            "[V4+ Styles]",
            "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour,",
            "Style: Default,Avenir Next Demi Bold,",
            "[Events]",
            "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
        ] {
            assert!(ass.contains(needle), "missing header piece: {needle}");
        }
        // Section order matters to libass parsers.
        assert!(ass.find("[V4+ Styles]") < ass.find("[Events]"));
    }

    #[test]
    fn k_values_are_word_durations_in_centiseconds() {
        let mut style = fill_style();
        style.max_words_per_line = 10;
        // Contiguous words, so no blank karaoke slots are inserted.
        let ws = words(&[("eins", 0, 300), ("zwei", 300, 750), ("drei", 750, 1000)]);

        let ass = build_ass(&ws, &style);

        assert_eq!(k_values(&ass), vec![30, 45, 25]);
    }

    #[test]
    fn silence_inside_a_line_becomes_a_blank_karaoke_slot() {
        let mut style = fill_style();
        style.max_words_per_line = 10;
        style.max_gap_ms = 5_000;
        // 200 ms of silence between the two words.
        let ws = words(&[("eins", 0, 300), ("zwei", 500, 900)]);

        let ass = build_ass(&ws, &style);

        // 30 for the first word, 20 for the pause, 40 for the second word.
        assert_eq!(k_values(&ass), vec![30, 20, 40]);
    }

    #[test]
    fn a_new_line_starts_after_n_words() {
        let mut style = fill_style();
        style.max_words_per_line = 3;
        style.max_line_ms = 60_000;
        let ws: Vec<Word> = (0..7)
            .map(|i| Word::new(format!("w{i}"), i * 200, i * 200 + 200))
            .collect();

        let ass = build_ass(&ws, &style);
        let lines = dialogue_lines(&ass);

        assert_eq!(lines.len(), 3, "7 words at 3 per line are 3 caption lines");
        assert_eq!(lines[0].matches("\\k").count(), 3);
        assert_eq!(lines[1].matches("\\k").count(), 3);
        assert_eq!(lines[2].matches("\\k").count(), 1, "last line holds the remainder");
    }

    #[test]
    fn empty_input_still_produces_a_valid_file() {
        let ass = build_ass(&[], &fill_style());

        assert!(ass.contains("[Script Info]"));
        assert!(ass.contains("[V4+ Styles]"));
        assert!(ass.contains("[Events]"));
        assert!(ass.trim_end().ends_with("Effect, Text"), "events section is declared but empty");
        assert_eq!(dialogue_lines(&ass).len(), 0, "no words means no Dialogue lines");
    }

    #[test]
    fn active_word_mode_redraws_the_line_once_per_word() {
        let mut style = StylePreset::BoldCenter.style();
        style.max_words_per_line = 3;
        style.max_line_ms = 60_000;
        assert_eq!(style.highlight, HighlightMode::ActiveWord);
        let ws = words(&[("eins", 0, 300), ("zwei", 300, 700), ("drei", 700, 1000)]);

        let ass = build_ass(&ws, &style);
        let lines = dialogue_lines(&ass);

        assert_eq!(lines.len(), 3, "one event per word");
        // Every event carries the full line, uppercased by this preset.
        for line in &lines {
            for w in ["EINS", "ZWEI", "DREI"] {
                assert!(line.contains(w), "line must repeat the whole caption: {line}");
            }
            assert_eq!(line.matches("\\k").count(), 1, "only the active word is timed");
        }
        // The active word carries the highlight colour and the scale pop.
        let hi = style.highlight_color.to_ass_inline();
        assert!(lines[1].contains(&format!("\\k40\\1c{hi}\\fscx112\\fscy112")));
    }

    #[test]
    fn timestamps_use_the_ass_hmmss_cc_format() {
        assert_eq!(ass_time(0), "0:00:00.00");
        assert_eq!(ass_time(1_500), "0:00:01.50");
        assert_eq!(ass_time(61_234), "0:01:01.23");
        assert_eq!(ass_time(3_723_450), "1:02:03.45");
    }

    #[test]
    fn braces_and_backslashes_in_a_word_cannot_break_the_line() {
        let mut style = fill_style();
        style.max_words_per_line = 10;
        let ws = words(&[("{evil}", 0, 200), ("a\\b", 200, 400)]);

        let ass = build_ass(&ws, &style);
        let line = dialogue_lines(&ass)[0];

        assert!(line.contains("(evil)"));
        assert!(line.contains("a/b"));
        // Exactly the two override blocks we wrote ourselves, no smuggled ones.
        assert_eq!(line.matches('{').count(), 2);
        assert_eq!(line.matches('}').count(), 2);
    }
}

#[cfg(test)]
mod readability_tests {
    use super::*;
    use crate::style::{StylePreset, SubtitleStyle};

    fn words(spans: &[(&str, u64, u64)]) -> Vec<Word> {
        spans
            .iter()
            .map(|(t, s, e)| Word { text: (*t).to_string(), start_ms: *s, end_ms: *e })
            .collect()
    }

    /// Parse "0:00:01.23" back into milliseconds so tests can assert on timing.
    fn parse_ts(ts: &str) -> u64 {
        let parts: Vec<&str> = ts.split(':').collect();
        let h: u64 = parts[0].parse().unwrap();
        let m: u64 = parts[1].parse().unwrap();
        let sec: f64 = parts[2].parse().unwrap();
        h * 3_600_000 + m * 60_000 + (sec * 1000.0).round() as u64
    }

    fn dialogue_spans(ass: &str) -> Vec<(u64, u64)> {
        ass.lines()
            .filter(|l| l.starts_with("Dialogue:"))
            .map(|l| {
                let f: Vec<&str> = l.split(',').collect();
                (parse_ts(f[1]), parse_ts(f[2]))
            })
            .collect()
    }

    #[test]
    fn a_short_final_line_is_held_long_enough_to_read() {
        let mut style = StylePreset::BoldCenter.style();
        style.min_line_ms = 1000;
        // Two quick words and then silence: without the hold this line would be
        // gone after 300ms.
        let ws = words(&[("kurz", 0, 150), ("weg", 150, 300)]);
        let spans = dialogue_spans(&build_ass(&ws, &style));
        let last = spans.last().copied().unwrap();
        assert!(
            last.1 - spans[0].0 >= 1000,
            "line should stay at least min_line_ms, got {:?}",
            last
        );
    }

    #[test]
    fn a_hold_never_runs_into_the_next_line() {
        let mut style = StylePreset::BoldCenter.style();
        style.min_line_ms = 2000;
        style.max_words_per_line = 1;
        style.max_gap_ms = 10;
        let ws = words(&[("eins", 0, 100), ("zwei", 400, 600)]);
        let spans = dialogue_spans(&build_ass(&ws, &style));
        assert!(spans.len() >= 2, "expected separate lines, got {spans:?}");
        for pair in spans.windows(2) {
            assert!(
                pair[0].1 <= pair[1].0,
                "line {:?} overlaps the next {:?}",
                pair[0],
                pair[1]
            );
        }
    }

    #[test]
    fn fast_speech_merges_into_readable_groups() {
        let mut style = StylePreset::BoldCenter.style();
        style.min_line_ms = 1000;
        style.max_words_per_line = 4;
        style.max_gap_ms = 60;
        // Six rapid words with small gaps: grouping must not produce one line
        // per word just because each gap slightly exceeds max_gap_ms.
        let ws = words(&[
            ("a", 0, 120),
            ("b", 200, 320),
            ("c", 400, 520),
            ("d", 600, 720),
            ("e", 800, 920),
            ("f", 1000, 1400),
        ]);
        let groups = group_words(&ws, &style);
        assert!(
            groups.len() <= 2,
            "fast speech should merge, got {} groups",
            groups.len()
        );
    }

    #[test]
    fn a_real_pause_after_a_long_enough_line_still_breaks() {
        let mut style = StylePreset::BoldCenter.style();
        style.min_line_ms = 800;
        style.max_words_per_line = 8;
        style.max_gap_ms = 500;
        let ws = words(&[("lang", 0, 900), ("danach", 2000, 2400)]);
        let groups = group_words(&ws, &style);
        assert_eq!(groups.len(), 2, "a real pause must start a new line");
    }
}
